/** "Technologies: ..." — a label and a colon, not prose that happens to contain one. */
const LABELLED_LINE = /^[^:]{1,30}\s*:\s/;

function renderSection(section: CvSection): string {
  const lines: string[] = [`\\section{${escapeLatex(section.heading)}}`];

  if (section.entries.length > 0) {
    lines.push("  \\resumeSubHeadingListStart");
    for (const entry of section.entries) {
      // A subheading with no second row is a project-style heading; the
      // template has a separate macro for exactly that shape.
      if (entry.subtitle === undefined) {
        lines.push(
          `    \\resumeProjectHeading`,
          `      {\\textbf{${escapeLatex(entry.title)}}}{${escapeLatex(entry.meta ?? "")}}`,
        );
      } else {
        lines.push(
          `    \\resumeSubheading`,
          `      {${escapeLatex(entry.title)}}{${escapeLatex(entry.meta ?? "")}}`,
          `      {${escapeLatex(entry.subtitle)}}{${escapeLatex(entry.subtitleMeta ?? "")}}`,
        );
      }
      if (entry.bullets.length > 0) {
        lines.push("      \\resumeItemListStart");
        for (const bullet of entry.bullets) {
          lines.push(`        \\resumeItem{${escapeLatex(bullet.text)}}`);
        }
        lines.push("      \\resumeItemListEnd");
      }
    }
    lines.push("  \\resumeSubHeadingListEnd");
  }

  // Two different things arrive as loose lines. A "Technologies: ..." line is
  // skills content and belongs in the template's compact labelled block; an
  // orphan bullet ("Cloud Computing with AWS Certificate") was a bullet in the
  // original and has to stay one, or Other Achievements silently loses its
  // markers on the way back out.
  const labelled = section.looseLines.filter((line) => LABELLED_LINE.test(line));
  const looseBullets = section.looseLines.filter((line) => !LABELLED_LINE.test(line));

  if (labelled.length > 0) {
    lines.push(
      " \\begin{itemize}[leftmargin=0.15in, label={}]",
      "    \\small{\\item{",
    );
    for (const line of labelled) {
      const [label, ...rest] = line.split(/\s*:\s*/);
      lines.push(`     \\textbf{${escapeLatex(label)}}{: ${escapeLatex(rest.join(": "))}} \\\\`);
    }
    lines.push("    }}", " \\end{itemize}");
  }

  if (looseBullets.length > 0) {
    lines.push("  \\resumeSubHeadingListStart", "      \\resumeItemListStart");
    for (const line of looseBullets) {
      lines.push(`        \\resumeItem{${escapeLatex(line)}}`);
    }
    lines.push("      \\resumeItemListEnd", "  \\resumeSubHeadingListEnd");
  }

  return lines.join("\n");
}

export function renderCvLatex(cv: ParsedCv): string {
  const header = [
    "\\begin{center}",
    `    \\textbf{\\Huge \\scshape ${escapeLatex(cv.name)}} \\\\ \\vspace{1pt}`,
    `    \\small ${escapeLatex(cv.contactLine)}`,
    "\\end{center}",
  ].join("\n");

  return [
    PREAMBLE,
    "\\begin{document}",
    "",
    header,
    "",
    ...cv.sections.map(renderSection),
    "",
    "\\end{document}",
    "",
  ].join("\n");
}

export interface BulletChange {
  section: string;
  entry: string;
  before: string;
  after: string;
}

/**
 * What a rewrite actually changed, bullet by bullet.
 *
 * Shown in full and never summarised: the point of the diff is that an invented
 * claim is visible rather than buried, and a summary is exactly where one would
 * hide. Structure is compared position-by-position because a rewrite may only
 * reword bullets, never add, remove or reorder them.
 */
export function diffCvBullets(before: ParsedCv, after: ParsedCv): BulletChange[] {
  const changes: BulletChange[] = [];
  for (const [sectionIndex, section] of before.sections.entries()) {
    const afterSection = after.sections[sectionIndex];
    if (afterSection === undefined) continue;
    for (const [entryIndex, entry] of section.entries.entries()) {
      const afterEntry = afterSection.entries[entryIndex];
      if (afterEntry === undefined) continue;
      for (const [bulletIndex, bullet] of entry.bullets.entries()) {
        const afterBullet = afterEntry.bullets[bulletIndex];
        if (afterBullet === undefined) continue;
        if (afterBullet.text === bullet.text) continue;
        changes.push({
          section: section.heading,
          entry: entry.title,
          before: bullet.text,
          after: afterBullet.text,
        });
      }
    }
  }
  return changes;
}

/**
 * Applies rewritten bullets onto a parsed CV by position.
 *
 * Rejects anything that would change the CV's shape — a rewrite is allowed to
 * change wording and nothing else. Adding a bullet is how an invented job would
 * get in, and the shape check is what makes that impossible rather than merely
 * discouraged.
 */
export function applyRewrittenBullets(
  cv: ParsedCv,
  replacements: { sectionIndex: number; entryIndex: number; bulletIndex: number; text: string }[],
): ParsedCv {
  const next: ParsedCv = {
    ...cv,
    sections: cv.sections.map((section) => ({
      ...section,
      entries: section.entries.map((entry) => ({
        ...entry,
        bullets: entry.bullets.map((bullet) => ({ ...bullet })),
      })),
      looseLines: [...section.looseLines],
    })),
  };

  for (const replacement of replacements) {
    const bullet =
      next.sections[replacement.sectionIndex]?.entries[replacement.entryIndex]?.bullets[
        replacement.bulletIndex
      ];
    if (bullet === undefined) {
      throw new Error(
        `Rewrite targets a bullet that does not exist (${replacement.sectionIndex}/${replacement.entryIndex}/${replacement.bulletIndex}).`,
      );
    }
    bullet.text = replacement.text;
  }
  return next;
}
