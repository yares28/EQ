import type { ParsedCv, CvSection } from "./cv-parse.ts";

/**
 * Re-emits a parsed CV as LaTeX in the template it came from.
 *
 * The source `.tex` of the imported PDF is gone, and a PDF has no editable text
 * structure, so "same format, different words" cannot be done by patching. It
 * can be done by regenerating: the layout comes from this template and only the
 * words come from the parsed content. That is why the parser keeps structure
 * rather than text.
 *
 * The template is Jake Gutierrez's widely-used resume class, which is what the
 * imported PDF was built with — same section rule, same small-caps headings,
 * same two-column subheadings.
 */

/**
 * LaTeX's ten special characters. Left unescaped, a single "%" in a bullet
 * comments out the rest of the line and a "&" is an alignment error — either
 * way the document silently stops compiling, which is a miserable thing to
 * hand someone as a copy-paste block.
 */
const LATEX_ESCAPES: Record<string, string> = {
  "\\": "\\textbackslash{}",
  "&": "\\&",
  "%": "\\%",
  $: "\\$",
  "#": "\\#",
  _: "\\_",
  "{": "\\{",
  "}": "\\}",
  "~": "\\textasciitilde{}",
  "^": "\\textasciicircum{}",
};

export function escapeLatex(value: string): string {
  return (
    value
      // One pass over every special at once. Escaping them in sequence meant a
      // backslash became \textbackslash{} and then the braces of that very
      // replacement were escaped again, producing \textbackslash\{\} — a
      // broken command in the middle of the document.
      .replace(/[\\&%$#_{}~^]/g, (character) => LATEX_ESCAPES[character] ?? character)
      // Not special, just the template's own conventions, so regenerated text
      // matches what is already in the document. A bare "|" in text mode does
      // not render as a pipe at all — the template writes it in math mode, and
      // the project titles ("Trakzi | Next.js, React") depend on it.
      .replace(/\|/g, "$|$")
      .replace(/–/g, "--")
      .replace(/—/g, "---")
  );
}

